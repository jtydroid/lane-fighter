// Assemble one deployable copy of the game and stamp its version.
//
// Usage: node scripts/build.js [--out DIR] [--sha SHA] [--release NAME]
//   --out      output directory (default: _site next to this repo)
//   --sha      commit being built (default: $GITHUB_SHA, else "local")
//   --release  release name, e.g. a tag like v0.1.0 (default: v<package.json version>)
//
// scripts/build-all.js calls this script *from each release tag's own code*,
// so keep these flags stable: old releases are rebuilt with their own copy.

import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const SITE_FILES = ['index.html', 'style.css', 'src'];

const args = process.argv.slice(2);
const opt = (name, fallback) => {
  const i = args.indexOf(name);
  return i >= 0 && args[i + 1] ? args[i + 1] : fallback;
};

const pkg = JSON.parse(await readFile(join(ROOT, 'package.json'), 'utf8'));
const out = resolve(opt('--out', join(ROOT, '_site')));
const sha = opt('--sha', process.env.GITHUB_SHA || 'local').slice(0, 7);
const release = opt('--release', `v${pkg.version}`);
const version = `${release}+${sha}`;

await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });
for (const f of SITE_FILES) await cp(join(ROOT, f), join(out, f), { recursive: true });

await writeFile(
  join(out, 'src', 'version.js'),
  '// Generated by scripts/build.js\n' +
    `export const RELEASE = ${JSON.stringify(release)};\n` +
    `export const VERSION = ${JSON.stringify(version)};\n`,
);

const { VARIANTS } = await import(pathToFileURL(join(ROOT, 'src', 'variants.js')).href);
const variants = Object.entries(VARIANTS).map(([id, v]) => ({ id, name: v.name }));

// Machine-readable build info, used by the version picker and smoke checks.
await writeFile(
  join(out, 'version.json'),
  JSON.stringify({ release, version, sha, variants, builtAt: new Date().toISOString() }, null, 2) + '\n',
);

// Tell GitHub Pages not to run Jekyll over the site.
await writeFile(join(out, '.nojekyll'), '');

console.log(`Built ${version} into ${out}`);
