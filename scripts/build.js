// Assemble the deployable site into _site/ and stamp the build version.
// Usage: node scripts/build.js
// Env (all optional, set by CI): GITHUB_SHA, GITHUB_RUN_NUMBER

import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const OUT = join(ROOT, '_site');
const SITE_FILES = ['index.html', 'style.css', 'src'];

const pkg = JSON.parse(await readFile(join(ROOT, 'package.json'), 'utf8'));
const sha = (process.env.GITHUB_SHA || 'local').slice(0, 7);
const run = process.env.GITHUB_RUN_NUMBER || '0';
const version = `v${pkg.version}+${sha}`;

await rm(OUT, { recursive: true, force: true });
await mkdir(OUT, { recursive: true });
for (const f of SITE_FILES) await cp(join(ROOT, f), join(OUT, f), { recursive: true });

await writeFile(
  join(OUT, 'src', 'version.js'),
  `// Generated by scripts/build.js\nexport const VERSION = ${JSON.stringify(version)};\n`,
);

// Machine-readable build info, used by the post-deploy smoke check.
await writeFile(
  join(OUT, 'version.json'),
  JSON.stringify({ version, sha, run: Number(run), builtAt: new Date().toISOString() }, null, 2) + '\n',
);

// Tell GitHub Pages not to run Jekyll over the site.
await writeFile(join(OUT, '.nojekyll'), '');

console.log(`Built ${version} into _site/`);
